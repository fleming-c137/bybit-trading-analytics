"""Request handling shared by the Vercel function (api/report.py) and the local server.

One endpoint, ``/api/report``:

* ``GET  ?action=sources``: which data sources this deployment offers
* ``GET  ?source=demo|owner|local&currency=&start=&end=&symbols=A,B&tilt=15``
* ``POST {"source": "api", "credentials": {...}, "filters": {...}}``: visitor's own read-only key
* ``POST {"source": "csv", "csv": "...", "filters": {...}}``: visitor's CSV export
* ``POST {"source": "dataset", "dataset": "<b64>", "filters": {...}}``: re-filter data returned earlier

Visitor credentials are used for that one request only. They are never stored,
logged or returned. The response carries the fetched data back to the browser
(``dataset``), so changing a filter doesn't need the key again.
"""

from __future__ import annotations

import logging
import os
import threading
from collections import OrderedDict
from datetime import datetime, timedelta, timezone
from functools import lru_cache
from pathlib import Path

import pandas as pd
import requests

from .client import BybitAPIError, BybitClient
from .config import PROJECT_ROOT, get_settings
from .report import (Dataset, Prepared, ReportError, build_report, dataset_from_b64, dataset_to_b64,
                     decode_dataset, prepare)
from .transform import normalize_api_transactions, normalize_closed_pnl, normalize_csv, normalize_klines

log = logging.getLogger(__name__)

SNAPSHOT_PATH = Path(os.getenv("BYBIT_SNAPSHOT_PATH", PROJECT_ROOT / "snapshots" / "owner.json.gz"))
MAX_API_DAYS = 90
MAX_CSV_BYTES = 4_000_000
_PREP_CACHE: OrderedDict[tuple, Prepared] = OrderedDict()
_LOCK = threading.Lock()


class ApiError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status
        self.message = message


# ---------------------------------------------------------------- sources
@lru_cache(maxsize=1)
def _demo_dataset(day: str) -> Dataset:
    from .demo import generate
    end = datetime.fromisoformat(day).replace(tzinfo=timezone.utc) + timedelta(hours=12)
    tx, cp, kl = generate(end=end)
    return Dataset(tx, cp, kl, {"kind": "demo", "label": "Demo account",
                                "detail": "Synthetic data generated by the project"})


def _owner_dataset() -> Dataset:
    if not SNAPSHOT_PATH.exists():
        raise ApiError(404, "No published account snapshot on this deployment yet.")
    return _owner_cached(SNAPSHOT_PATH.stat().st_mtime)


@lru_cache(maxsize=1)
def _owner_cached(_mtime: float) -> Dataset:
    ds = decode_dataset(SNAPSHOT_PATH.read_bytes())
    ds.meta.setdefault("kind", "owner")
    ds.meta.setdefault("label", "Published account")
    return ds


def _local_dataset() -> Dataset:
    settings = get_settings()
    if not settings.db_path.exists():
        raise ApiError(404, "No synced database on this machine. Run `python -m bybit_analytics sync` first.")
    return _local_cached(str(settings.db_path), settings.db_path.stat().st_mtime)


@lru_cache(maxsize=1)
def _local_cached(path: str, _mtime: float) -> Dataset:
    from .storage import Store
    store = Store(path)
    return Dataset(store.load_transactions(), store.load_closed_pnl(), store.load_klines(),
                   {"kind": "local", "label": "This machine", "detail": "Synced SQLite database",
                    "last_sync": store.get_meta("last_sync")})


def sources(allow_local: bool) -> dict:
    owner = SNAPSHOT_PATH.exists()
    local = allow_local and get_settings().db_path.exists()
    meta = {}
    if owner:
        try:
            meta = _owner_dataset().meta
        except Exception:  # a broken snapshot shouldn't take the site down
            owner = False
    default = "local" if local else "owner" if owner else "demo"
    return {"owner": owner, "owner_meta": meta, "local": local, "demo": True, "api": True, "csv": True,
            "default": default, "max_api_days": MAX_API_DAYS}


def _klines_for(tx: pd.DataFrame, client: BybitClient | None = None) -> pd.DataFrame:
    if tx.empty:
        return pd.DataFrame()
    client = client or BybitClient()
    start = tx["time"].min().to_pydatetime() - timedelta(days=30)
    try:
        return normalize_klines(client.klines("BTCUSDT", start, datetime.now(timezone.utc)), "BTCUSDT")
    except Exception as exc:  # market context is optional
        log.warning("Skipping BTC candles: %s", exc)
        return pd.DataFrame()


def fetch_api_dataset(creds: dict) -> Dataset:
    key = str(creds.get("api_key", "")).strip()
    secret = str(creds.get("api_secret", "")).strip()
    if not key or not secret:
        raise ApiError(400, "Enter both the API key and the API secret.")
    try:
        days = int(creds.get("days", 30))
    except (TypeError, ValueError):
        days = 30
    days = max(1, min(days, MAX_API_DAYS))
    base = "https://api-testnet.bybit.com" if creds.get("testnet") else "https://api.bybit.com"
    client = BybitClient(key, secret, base, max_retries=3)
    end = datetime.now(timezone.utc)
    start = end - timedelta(days=days)
    try:
        tx = normalize_api_transactions(list(client.transaction_log(start, end)))
        cp = normalize_closed_pnl(list(client.closed_pnl(start, end)))
    except BybitAPIError as exc:
        hints = {10003: "The API key is not valid.", 10004: "The API secret doesn't match the key.",
                 10005: "The key needs read permission for Unified Trading.",
                 10010: "This key is IP-restricted, and this server's IP isn't on its allow list.",
                 33004: "This API key has expired."}
        code = getattr(exc, "code", None)
        raise ApiError(400, hints.get(code, f"Bybit rejected the request: {exc}")) from exc
    except requests.HTTPError as exc:
        status = exc.response.status_code if exc.response is not None else 502
        if status == 403:
            raise ApiError(502, "Bybit blocked this server's region. Run the project locally instead.") from exc
        raise ApiError(502, f"Bybit returned HTTP {status}.") from exc
    except requests.RequestException as exc:
        raise ApiError(502, "Couldn't reach Bybit. Try again in a moment.") from exc
    if tx.empty:
        raise ApiError(404, f"No transactions in the last {days} days on this account.")
    return Dataset(tx, cp, _klines_for(tx, client), {
        "kind": "api", "label": "Your account", "detail": f"Live from the Bybit API, last {days} days",
        "fetched_at": end.isoformat(),
    })


def csv_dataset(text: str) -> Dataset:
    if not text:
        raise ApiError(400, "The CSV file is empty.")
    if len(text.encode()) > MAX_CSV_BYTES:
        raise ApiError(413, "That CSV is over 4 MB. Run the project locally to analyse large exports.")
    import io
    try:
        tx = normalize_csv(pd.read_csv(io.StringIO(text)))
    except Exception as exc:
        raise ApiError(400, "This doesn't look like a Bybit UTA transaction log export.") from exc
    return Dataset(tx, pd.DataFrame(), _klines_for(tx), {
        "kind": "csv", "label": "Your CSV export", "detail": f"{len(tx):,} rows uploaded"})


# ---------------------------------------------------------------- handler
def _prepared(cache_key: tuple | None, ds: Dataset, currency: str | None) -> Prepared:
    if cache_key is None:
        return prepare(ds, currency)
    key = (*cache_key, currency)
    with _LOCK:
        if key in _PREP_CACHE:
            _PREP_CACHE.move_to_end(key)
            return _PREP_CACHE[key]
    p = prepare(ds, currency)
    with _LOCK:
        _PREP_CACHE[key] = p
        _PREP_CACHE[(*cache_key, p.currency)] = p
        while len(_PREP_CACHE) > 8:
            _PREP_CACHE.popitem(last=False)
    return p


def _filters(raw: dict) -> dict:
    symbols = raw.get("symbols") or []
    if isinstance(symbols, str):
        symbols = [s for s in symbols.split(",") if s]
    try:
        tilt = float(raw.get("tilt") or raw.get("tilt_window") or 15)
    except (TypeError, ValueError):
        tilt = 15.0
    return {"currency": raw.get("currency") or None, "start": raw.get("start") or None,
            "end": raw.get("end") or None, "symbols": [str(s) for s in symbols][:200],
            "tilt_window": max(1.0, min(tilt, 240.0))}


def handle(params: dict, allow_local: bool = False) -> tuple[int, dict, dict]:
    """Return (status, json body, extra headers)."""
    try:
        if params.get("action") == "sources":
            return 200, sources(allow_local), {"Cache-Control": "no-store"}

        source = params.get("source") or "demo"
        f = _filters(params.get("filters") or params)
        headers = {"Cache-Control": "no-store"}
        returned_dataset = None

        if source == "demo":
            day = datetime.now(timezone.utc).date().isoformat()
            ds, key = _demo_dataset(day), ("demo", day)
            headers = {"Cache-Control": "public, max-age=300, s-maxage=3600"}
        elif source == "owner":
            ds = _owner_dataset()
            key = ("owner", SNAPSHOT_PATH.stat().st_mtime)
            headers = {"Cache-Control": "public, max-age=300, s-maxage=86400, stale-while-revalidate=86400"}
        elif source == "local":
            if not allow_local:
                raise ApiError(404, "This source is only available when you run the dashboard locally.")
            ds = _local_dataset()
            key = ("local", get_settings().db_path.stat().st_mtime)
        elif source == "api":
            ds, key = fetch_api_dataset(params.get("credentials") or {}), None
            returned_dataset = ds
        elif source == "csv":
            ds, key = csv_dataset(params.get("csv") or ""), None
            returned_dataset = ds
        elif source == "dataset":
            ds, key = dataset_from_b64(params.get("dataset") or ""), None
        else:
            raise ApiError(400, f"Unknown source '{source}'.")

        p = _prepared(key, ds, f["currency"])
        body = {"report": build_report(p, f["start"], f["end"], f["symbols"], f["tilt_window"])}
        if returned_dataset is not None:
            body["dataset"] = dataset_to_b64(returned_dataset)
        return 200, body, headers
    except ApiError as exc:
        return exc.status, {"error": exc.message}, {"Cache-Control": "no-store"}
    except ReportError as exc:
        return 400, {"error": str(exc)}, {"Cache-Control": "no-store"}
    except Exception:
        log.exception("Report failed")
        return 500, {"error": "Something went wrong while building the report."}, {"Cache-Control": "no-store"}
